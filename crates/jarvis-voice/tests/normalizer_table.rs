#[test]
fn normalizer_table() {
    let n = SpeechNormalizer::new();
    let mut failures = Vec::new();
    for (input, expected) in CASES {
        // Знаки ударения в английских словах (U+0301, для произношения) проверяются в english.rs; здесь — текст.
        let got = n.normalize(input).replace('\u{301}', "");
        if got != *expected {
            failures.push(format!("  {input:?}\n    ожидалось: {expected:?}\n    получено:  {got:?}"));
        }
    }
    assert!(CASES.len() >= 60, "кейсов должно быть не меньше 60");
    assert!(failures.is_empty(), "{} из {} кейсов не совпали:\n{}", failures.len(), CASES.len(), failures.join("\n"));
}

#[test]
fn normalizer_is_idempotent_on_plain_words() {
    let n = SpeechNormalizer::new();
    let s = n.normalize("Сэр, всё готово. Открыть браузер?");
    assert_eq!(s, "Сэр, всё готово. Открыть браузер?");
    assert_eq!(n.normalize(&s), s);
    assert!(SpeechNormalizer::is_speakable("пять"));
    assert!(!SpeechNormalizer::is_speakable("… ✅ —"));
    assert_eq!(n.normalize("✅"), "");
}
